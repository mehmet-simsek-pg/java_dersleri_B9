package gun24;

public class AccessModifiersKonusu {
    /**
     * Access Modifiers :
     * 1. public -> ile bir degiskeni, sinifi ya da metodu tanimlarsam
     * projenin her yerinden bunlara ulasabilirim.

     * 2. private -> ile bir degiskeni ya da metodu tanimlarsam
     * sadece ayni class icinden ulasabiliriz.

     * 3. protected -> ile ayni paket icinden erisilebilir. Farkli paketler
     * icinden erismek icin ise kalitim yoluyla miras birakmis olmasi gerekir.

     * 4. default -> her hangi bir modifier yazmazsak bunu java default olarak
     * algilar. default olanlara sadece ayni paket icerisinden ulasilabilir.
     * */
}
